package com.capstone.nik.mixology.data

import android.app.Activity
import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.capstone.nik.mixology.R
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.tasks.await
import javax.inject.Inject
import javax.inject.Singleton

sealed interface GoogleAuthResult {
    /** Firebase ID token for the signed-in Google account, ready for `POST /auth/google`. */
    data class Success(val firebaseIdToken: String) : GoogleAuthResult
    data object Cancelled : GoogleAuthResult
    data class Failure(val detail: String) : GoogleAuthResult
}

interface GoogleAuth {
    /** Shows the Google account picker over [activity] and signs in to Firebase. */
    suspend fun signIn(activity: Activity): GoogleAuthResult

    /** Signs out of Firebase so the next Google sign-in starts fresh. */
    fun signOut()
}

@Singleton
class FirebaseGoogleAuth @Inject constructor(
    @ApplicationContext private val context: Context,
) : GoogleAuth {

    override suspend fun signIn(activity: Activity): GoogleAuthResult {
        // Generated by the google-services plugin from the web OAuth client in google-services.json.
        val option = GetSignInWithGoogleOption.Builder(
            context.getString(R.string.default_web_client_id),
        ).build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        return try {
            val credential = CredentialManager.create(activity).getCredential(activity, request).credential
            if (credential !is CustomCredential ||
                credential.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                return failure()
            }
            val google = GoogleIdTokenCredential.createFrom(credential.data)
            val firebaseCredential = GoogleAuthProvider.getCredential(google.idToken, null)
            val user = FirebaseAuth.getInstance().signInWithCredential(firebaseCredential).await().user
                ?: return failure()
            val token = user.getIdToken(true).await().token ?: return failure()
            GoogleAuthResult.Success(token)
        } catch (error: CancellationException) {
            throw error
        } catch (error: GetCredentialCancellationException) {
            GoogleAuthResult.Cancelled
        } catch (error: NoCredentialException) {
            GoogleAuthResult.Failure(context.getString(R.string.auth_google_no_account))
        } catch (error: GetCredentialException) {
            failure()
        } catch (error: GoogleIdTokenParsingException) {
            failure()
        } catch (error: Exception) {
            failure()
        }
    }

    override fun signOut() {
        FirebaseAuth.getInstance().signOut()
    }

    private fun failure() = GoogleAuthResult.Failure(context.getString(R.string.auth_google_failed))
}
